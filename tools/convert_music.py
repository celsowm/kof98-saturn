#!/usr/bin/env python3
"""Convert real game audio (a WAV captured from the KOF98 oracle's YM2610/Z80
emulation) into the raw interleaved S16BE stream that LibSaturn's built-in disc
music feed (sat_disc_stream_music_start) plays, plus a small C asset header.

This is deliberately dependency-free (no ffmpeg, no audioop): it reads a PCM16
WAV, slices a time range, resamples to the SCSP-friendly rate with linear
interpolation, applies short fades so the loop does not click, and writes
big-endian 16-bit samples.

Output layout: `channels`-interleaved S16 big-endian frames, which is exactly
what sat_disc_stream_music_start(sample_bytes=2) expects.
"""
from __future__ import annotations

import argparse
import struct
import sys
import wave
from array import array
from pathlib import Path


def read_pcm16_wav(path: Path):
    with wave.open(str(path), "rb") as w:
        if w.getsampwidth() != 2:
            raise SystemExit(f"{path}: expected 16-bit PCM WAV")
        channels = w.getnchannels()
        rate = w.getframerate()
        frames = w.getnframes()
        raw = w.readframes(frames)
    samples = array("h")
    samples.frombytes(raw)  # WAV PCM is little-endian
    if sys.byteorder != "little":
        samples.byteswap()  # decode little-endian bytes into native values
    return samples, channels, rate, frames


def slice_frames(samples: array, channels: int, rate: int, start_ms: int, duration_ms: int):
    first = start_ms * rate // 1000
    last = len(samples) // channels
    if duration_ms:
        last = min(last, first + duration_ms * rate // 1000)
    if first >= last:
        raise SystemExit("audio clip is empty")
    return samples[first * channels:last * channels], first, last


def resample(samples: array, channels: int, src_rate: int, dst_rate: int):
    """Linear-interpolation resample of interleaved S16 (big-endian array)."""
    if src_rate == dst_rate:
        return samples
    src_frames = len(samples) // channels
    dst_frames = max(1, int(round(src_frames * dst_rate / src_rate)))
    out = array("h", [0]) * (dst_frames * channels)
    for c in range(channels):
        for i in range(dst_frames):
            pos = i * src_rate / dst_rate
            j = int(pos)
            if j >= src_frames - 1:
                out[i * channels + c] = samples[(src_frames - 1) * channels + c]
                continue
            frac = pos - j
            a = samples[j * channels + c]
            b = samples[(j + 1) * channels + c]
            out[i * channels + c] = int(a + (b - a) * frac)
    return out


def apply_fade(samples: array, channels: int, rate: int, fade_ms: int):
    n = min(rate * fade_ms // 1000, len(samples) // channels // 2)
    if n <= 0:
        return
    for i in range(n):
        g = i / n
        for c in range(channels):
            k = i * channels + c
            samples[k] = int(samples[k] * g)
            m = len(samples) - 1 - k
            samples[m] = int(samples[m] * g)


def write_be(path: Path, samples: array):
    # array holds native values; produce big-endian bytes on disk.
    if sys.byteorder != "big":
        samples.byteswap()  # native little -> big-endian byte order
    path.write_bytes(samples.tobytes())
    if sys.byteorder != "big":
        samples.byteswap()  # restore native order


def main() -> int:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--input", required=True, type=Path)
    p.add_argument("--output-audio", required=True, type=Path)
    p.add_argument("--output-header", required=True, type=Path)
    p.add_argument("--name", required=True)
    p.add_argument("--sample-rate", type=int, default=44100)
    p.add_argument("--start-ms", type=int, default=0)
    p.add_argument("--duration-ms", type=int, default=0)
    p.add_argument("--fade-ms", type=int, default=8)
    args = p.parse_args()

    if args.sample_rate <= 0:
        p.error("sample rate must be positive")
    if not args.input.is_file():
        p.error(f"input not found: {args.input}")

    samples, channels, src_rate, src_frames = read_pcm16_wav(args.input)
    clipped, first, last = slice_frames(samples, channels, src_rate, args.start_ms, args.duration_ms)
    resampled = resample(clipped, channels, src_rate, args.sample_rate)
    apply_fade(resampled, channels, args.sample_rate, args.fade_ms)
    frames = len(resampled) // channels
    data_bytes = frames * channels * 2

    args.output_audio.parent.mkdir(parents=True, exist_ok=True)
    write_be(args.output_audio, resampled)

    prefix = "KOF_" + args.name.upper()
    guard = prefix + "_ASSETS_H"
    args.output_header.write_text(
        "\n".join([
            f"#ifndef {guard}",
            f"#define {guard}",
            "",
            "/* Generated by tools/convert_music.py from real KOF98 oracle audio.",
            " * Raw interleaved S16 big-endian for sat_disc_stream_music_start. */",
            f"#define {prefix}_SAMPLE_RATE {args.sample_rate}u",
            f"#define {prefix}_CHANNELS {channels}u",
            f"#define {prefix}_FRAMES {frames}u",
            f"#define {prefix}_BYTES {data_bytes}u",
            "",
            f"#endif /* {guard} */",
            "",
        ]),
        encoding="ascii",
    )
    print(
        f"[music] {args.name}: {frames} frames, {data_bytes} bytes, "
        f"{args.sample_rate} Hz, {channels} ch, from {src_rate} Hz "
        f"[{args.start_ms}..{args.start_ms + args.duration_ms} ms]"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())