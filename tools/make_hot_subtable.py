#!/usr/bin/env python3
"""Extract a hot sub-table from the full game recomp page map.

The full map (56,748 entries, 681 KB) does not fit WRAM alongside the app
(~816 KB used of 983 KB). This tool builds a compact sub-table for WRAM:
the reset-PC neighborhood plus the profile-hot routines' entries, sized to
a byte budget. Misses fall back to the interpreter (correct) or the
disc-backed full map (slow) — the sub-table is a cache over the full map,
not a replacement.

The sub-table is emitted as a C file (const array + count) using the same
ng_recomp_page_entry_t layout, plus a small manifest for the overlay loader.

Usage:
  python tools/make_hot_subtable.py --dir <generated> --prefix game_ \
      --out <out.c> --budget 167000 [--profile <csv> ...] \
      [--reset-pc 0x000000]
"""
import argparse
import csv
import re
from pathlib import Path

ENTRY_RE = re.compile(r"\{0x([0-9A-Fa-f]+)u, (\w+), (\d+)u\},")


def parse_entries(path: Path):
    entries = []
    for line in path.read_text(errors="replace").splitlines():
        m = ENTRY_RE.search(line)
        if m:
            entries.append((int(m.group(1), 16), m.group(2), int(m.group(3))))
    entries.sort(key=lambda e: e[0])
    return entries


def profile_hits(paths):
    hits = {}
    for path in paths:
        with path.open(newline="") as f:
            if not f.readline().strip().startswith("# kof-native-profile-v1"):
                raise SystemExit(f"{path}: bad profile identity line")
            for row in csv.DictReader(f):
                key = int(row["key"], 16)
                hits[key] = hits.get(key, 0) + int(row["hits"])
    return hits


def main() -> int:
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--dir", type=Path, required=True)
    p.add_argument("--prefix", default="game_")
    p.add_argument("--out", type=Path, required=True)
    p.add_argument("--budget", type=int, required=True, help="sub-table byte budget")
    p.add_argument("--profile", type=Path, action="append", default=[])
    p.add_argument("--reset-pc", type=lambda x: int(x, 0), default=0x000000)
    a = p.parse_args()

    entries = parse_entries(a.dir / f"{a.prefix}recomp_pages.c")
    if not entries:
        raise SystemExit("no entries in page map")
    hits = profile_hits(a.profile) if a.profile else {}

    # hot set: reset-PC neighborhood (same 4 KiB page) + profile-hot entries
    hot_pages = {(a.reset_pc >> 12) & 0xFF}  # cart 0 page of the reset PC
    hot_addrs = set()
    for addr, name, page in entries:
        if (addr >> 12) == (a.reset_pc >> 12) or hits.get(addr, 0) > 0:
            hot_addrs.add(addr)
            hot_pages.add(page)

    # budget: 12 B per entry (addr+fn+page), keep the densest prefix by addr
    entry_bytes = 12
    max_entries = max(1, a.budget // entry_bytes)
    selected = [e for e in entries if e[0] in hot_addrs][:max_entries]
    used = len(selected) * entry_bytes

    a.out.parent.mkdir(parents=True, exist_ok=True)
    out = ["/* Generated by tools/make_hot_subtable.py. Local build only. */",
           '#include "game_recomp_pages.h"',
           "",
           f"/* Hot sub-table: {len(selected)} of {len(entries)} entries,",
           f" * {used} of {a.budget} budget bytes. Misses fall back to the",
           " * disc-backed full map (or the interpreter). */",
           "const ng_recomp_page_entry_t ng_hot_pages[] = {"]
    for addr, name, page in selected:
        out.append(f"    {{0x{addr:06X}u, {name}, {page}u}},")
    out.append("};")
    out.append(f"const size_t ng_hot_pages_count = {len(selected)};")
    a.out.write_text("\n".join(out) + "\n")
    print(f"[hot-subtable] {len(selected)}/{len(entries)} entries, "
          f"{used} bytes (budget {a.budget}), {len(hot_pages)} pages touched")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())